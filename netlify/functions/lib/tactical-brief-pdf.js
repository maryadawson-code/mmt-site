// ============================================================
// tactical-brief-pdf.js — PDFKit PDF generator for Tactical Brief
//
// Generates a branded PDF from the synthesized research output.
// Returns a Buffer containing the PDF bytes.
//
// Uses bufferPages: true so all pages remain accessible for
// post-processing (TOC, footers, page numbers). Pages are
// flushed via doc.flushPages() before doc.end().
// ============================================================

const PDFDocument = require("pdfkit");
const path = require("path");
const fs = require("fs");

// Brand colors
const CYAN = "#00E5FA";
const NAVY = "#00050F";
const SLATE = "#0A1628";
const WHITE = "#FFFFFF";
const MUTED = "#B0B8C4";
const GREEN = "#00FF85";

// Safety limits
const MAX_SYNTHESIS_CHARS = 60000;
const MAX_CITATIONS = 20;
const MAX_SECTION_CHARS = 10000;

// Confidence badge colors
const CONFIDENCE_COLORS = {
  HIGH: { bg: "#dcfce7", text: "#166534" },
  MEDIUM: { bg: "#fef9c3", text: "#854d0e" },
  LOW: { bg: "#fee2e2", text: "#991b1b" },
  UNVERIFIED: { bg: "#f3f4f6", text: "#6b7280" },
};

/**
 * Safely coerce a value to a non-null trimmed string.
 */
function safeText(val) {
  return (val || "").toString().trim();
}

/**
 * Try to load the MMT logo from the project root.
 * Returns a Buffer or null if not found.
 */
function loadLogo() {
  try {
    // Resolve relative to this file: lib/ -> functions/ -> netlify/ -> project root
    const logoPath = path.resolve(__dirname, "..", "..", "..", "mmt-logo.png");
    if (fs.existsSync(logoPath)) {
      return fs.readFileSync(logoPath);
    }
  } catch {
    // Non-blocking — skip logo
  }
  return null;
}

/**
 * Truncate text to maxChars with an ellipsis note.
 */
function truncate(text, maxChars, label = "content") {
  if (!text || text.length <= maxChars) return text || "";
  return text.substring(0, maxChars) + `\n\n... [${label} truncated — full analysis available upon request]`;
}

/**
 * Extract section headers from synthesis text for TOC generation.
 * Returns array of { title, lineIndex }.
 */
function extractSectionHeaders(lines) {
  const headers = [];
  for (let i = 0; i < lines.length; i++) {
    const trimmed = lines[i].trim();
    if (/^#{1,3}\s/.test(trimmed)) {
      headers.push({ title: trimmed.replace(/^#+\s*/, ""), lineIndex: i });
    } else if (/^[A-Z][A-Z &\/\-]+$/.test(trimmed) && trimmed.length > 3 && trimmed.length < 80) {
      headers.push({ title: trimmed, lineIndex: i });
    }
  }
  return headers;
}

/**
 * Check if y position needs a new page, and if so, add one.
 * Returns the new y position.
 */
function checkPageBreak(doc, y, needed = 80) {
  if (y > doc.page.height - needed) {
    doc.addPage();
    return 60;
  }
  return y;
}

/**
 * Draw the disclaimer footer on a specific page.
 */
function drawFooter(doc, pageNum, totalPages) {
  doc
    .font("Helvetica")
    .fontSize(7)
    .fillColor("#999999")
    .text(
      "This report was generated by Mission Meets Tech AI-assisted research. All claims should be independently verified. Sources are cited where available.",
      60,
      doc.page.height - 45,
      { width: doc.page.width - 120, align: "center" }
    );
  doc
    .font("Helvetica")
    .fontSize(7)
    .fillColor("#bbbbbb")
    .text(
      `Page ${pageNum} of ${totalPages}  |  Mission Meets Tech  |  missionmeetstech.com  |  Confidential`,
      60,
      doc.page.height - 30,
      { width: doc.page.width - 120, align: "center" }
    );
}

/**
 * Render a confidence badge inline if found in text.
 * Returns the text with badges stripped (they're rendered separately).
 */
function renderConfidenceBadge(doc, text, x, y) {
  const match = text.match(/\[(HIGH|MEDIUM|LOW|UNVERIFIED)\]/i);
  if (!match) return null;

  const level = match[1].toUpperCase();
  const colors = CONFIDENCE_COLORS[level] || CONFIDENCE_COLORS.UNVERIFIED;
  const badgeWidth = level.length * 5.5 + 12;

  // Draw badge
  doc
    .roundedRect(x, y - 2, badgeWidth, 14, 3)
    .fill(colors.bg);
  doc
    .font("Helvetica-Bold")
    .fontSize(7)
    .fillColor(colors.text)
    .text(level, x + 6, y, { width: badgeWidth - 12 });

  return {
    cleanText: text.replace(/\s*\[(HIGH|MEDIUM|LOW|UNVERIFIED)\]\s*/gi, " ").trim(),
    badgeWidth: badgeWidth + 6,
  };
}

// ============================================================
// COVER PAGE
// ============================================================
function renderCoverPage(doc, { name, company, topic, audience, generatedAt, logo }) {
  // Navy header block
  doc
    .rect(0, 0, doc.page.width, 200)
    .fill(NAVY);

  // Logo (if available)
  let logoBottomY = 40;
  if (logo) {
    try {
      doc.image(logo, 60, 35, { width: 40, height: 40 });
      logoBottomY = 80;
    } catch {
      // Skip logo on error
    }
  }

  // Title
  doc
    .font("Helvetica-Bold")
    .fontSize(32)
    .fillColor(CYAN)
    .text("MARKETPULSE", logo ? 110 : 60, 40, { width: doc.page.width - 170 });

  doc
    .font("Helvetica")
    .fontSize(11)
    .fillColor(MUTED)
    .text("Mission Meets Tech — Federal Health IT Market Intelligence", logo ? 110 : 60, 80, {
      width: doc.page.width - 170,
    });

  // Accent line
  doc
    .moveTo(60, 170)
    .lineTo(doc.page.width - 60, 170)
    .strokeColor(CYAN)
    .lineWidth(2)
    .stroke();

  // Classification banner
  doc
    .font("Helvetica-Bold")
    .fontSize(9)
    .fillColor("#94a3b8")
    .text("UNCLASSIFIED // FOR OFFICIAL USE ONLY", 60, 185, {
      width: doc.page.width - 120,
      align: "center",
    });

  // Topic block
  let y = 230;

  doc
    .font("Helvetica-Bold")
    .fontSize(12)
    .fillColor("#999999")
    .text("RESEARCH TOPIC", 60, y);
  y += 20;

  doc
    .font("Helvetica")
    .fontSize(13)
    .fillColor("#1a1a1a")
    .text(safeText(topic), 60, y, { width: doc.page.width - 120 });
  y = doc.y + 24;

  // Metadata table
  const fields = [
    ["PREPARED FOR", company ? `${safeText(name)}, ${safeText(company)}` : safeText(name)],
    ["DATE", new Date(generatedAt || Date.now()).toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" })],
  ];
  if (audience) {
    fields.push(["AUDIENCE", safeText(audience)]);
  }

  for (const [label, value] of fields) {
    doc
      .font("Helvetica-Bold")
      .fontSize(9)
      .fillColor("#666666")
      .text(`${label}: `, 60, y, { continued: true })
      .font("Helvetica")
      .text(value);
    y = doc.y + 6;
  }

  // Divider before content
  y += 16;
  doc
    .moveTo(60, y)
    .lineTo(doc.page.width - 60, y)
    .strokeColor("#e0e0e0")
    .lineWidth(0.5)
    .stroke();
}

// ============================================================
// TABLE OF CONTENTS
// ============================================================
function renderTocPage(doc, tocEntries) {
  doc.addPage();

  doc
    .font("Helvetica-Bold")
    .fontSize(18)
    .fillColor(NAVY)
    .text("TABLE OF CONTENTS", 60, 60);

  let y = 100;

  doc
    .moveTo(60, y - 4)
    .lineTo(doc.page.width - 60, y - 4)
    .strokeColor(CYAN)
    .lineWidth(1.5)
    .stroke();
  y += 12;

  for (const entry of tocEntries) {
    if (y > doc.page.height - 80) break; // Safety

    const titleWidth = doc.page.width - 180;
    const pageNumX = doc.page.width - 90;

    // Section title
    doc
      .font("Helvetica")
      .fontSize(11)
      .fillColor("#333333")
      .text(entry.title, 60, y, { width: titleWidth });

    // Dotted leader
    const textEnd = Math.min(60 + doc.widthOfString(entry.title, { font: "Helvetica", fontSize: 11 }), pageNumX - 20);
    doc
      .font("Helvetica")
      .fontSize(11)
      .fillColor("#cccccc")
      .text(
        ".".repeat(Math.max(0, Math.floor((pageNumX - textEnd - 20) / 4))),
        textEnd + 4,
        y
      );

    // Page number
    doc
      .font("Helvetica-Bold")
      .fontSize(11)
      .fillColor(NAVY)
      .text(String(entry.pageNum), pageNumX, y, { width: 30, align: "right" });

    y += 22;
  }
}

// ============================================================
// MAIN CONTENT RENDERER
// ============================================================
function renderContent(doc, synthesis, tocEntries) {
  doc.addPage();
  let y = 60;

  const lines = synthesis.split("\n");
  let currentSectionCharCount = 0;
  let sectionTruncated = false;

  for (const line of lines) {
    const trimmed = line.trim();

    y = checkPageBreak(doc, y);

    if (!trimmed) {
      y += 8;
      continue;
    }

    // Section headers (## or ALL CAPS)
    if (/^#{1,3}\s/.test(trimmed)) {
      const headerText = trimmed.replace(/^#+\s*/, "");
      currentSectionCharCount = 0;
      sectionTruncated = false;

      y = checkPageBreak(doc, y, 100);
      y += 6;

      // Record TOC entry with current page number
      const range = doc.bufferedPageRange();
      const currentPage = range.start + range.count; // 1-indexed page
      tocEntries.push({ title: headerText.toUpperCase(), pageNum: currentPage });

      // Check for confidence badge in header
      const badge = renderConfidenceBadge(doc, headerText, doc.page.width - 140, y + 2);

      doc
        .font("Helvetica-Bold")
        .fontSize(13)
        .fillColor(NAVY)
        .text(badge ? badge.cleanText.toUpperCase() : headerText.toUpperCase(), 60, y, {
          width: doc.page.width - (badge ? 180 : 120),
        });
      y = doc.y + 8;

      // Accent underline
      doc
        .moveTo(60, y)
        .lineTo(180, y)
        .strokeColor(CYAN)
        .lineWidth(1.5)
        .stroke();
      y += 12;
    } else if (/^[A-Z][A-Z &\/\-]+$/.test(trimmed) && trimmed.length > 3 && trimmed.length < 80) {
      // ALL CAPS section header
      currentSectionCharCount = 0;
      sectionTruncated = false;

      y = checkPageBreak(doc, y, 100);
      y += 6;

      const range = doc.bufferedPageRange();
      const currentPage = range.start + range.count;
      tocEntries.push({ title: trimmed, pageNum: currentPage });

      doc
        .font("Helvetica-Bold")
        .fontSize(13)
        .fillColor(NAVY)
        .text(trimmed, 60, y, { width: doc.page.width - 120 });
      y = doc.y + 8;

      doc
        .moveTo(60, y)
        .lineTo(180, y)
        .strokeColor(CYAN)
        .lineWidth(1.5)
        .stroke();
      y += 12;
    } else {
      // Track section length for truncation
      currentSectionCharCount += trimmed.length;
      if (currentSectionCharCount > MAX_SECTION_CHARS && !sectionTruncated) {
        sectionTruncated = true;
        doc
          .font("Helvetica-Oblique")
          .fontSize(9)
          .fillColor("#94a3b8")
          .text("[Section truncated for brevity — full analysis available in research output]", 60, y, {
            width: doc.page.width - 120,
          });
        y = doc.y + 8;
        continue;
      }
      if (sectionTruncated) continue;

      if (/^\d+\.\s/.test(trimmed) || /^[-•]\s/.test(trimmed)) {
        // Numbered or bulleted list item
        const bulletText = trimmed.replace(/^[-•]\s*/, "").replace(/^\d+\.\s*/, "");
        const bullet = /^\d+\./.test(trimmed) ? trimmed.match(/^\d+\./)[0] : "\u2022";

        // Check for confidence badge
        const badge = renderConfidenceBadge(doc, bulletText, doc.page.width - 140, y + 1);

        doc
          .font("Helvetica-Bold")
          .fontSize(10)
          .fillColor("#333333")
          .text(bullet, 68, y, { width: 20 });

        doc
          .font("Helvetica")
          .fontSize(10)
          .fillColor("#1a1a1a")
          .text(badge ? badge.cleanText : bulletText, 90, y, {
            width: doc.page.width - (badge ? 200 : 150),
          });
        y = doc.y + 6;
      } else if (trimmed.startsWith("**") && trimmed.endsWith("**")) {
        // Bold line
        doc
          .font("Helvetica-Bold")
          .fontSize(10)
          .fillColor("#1a1a1a")
          .text(trimmed.replace(/\*\*/g, ""), 60, y, { width: doc.page.width - 120 });
        y = doc.y + 6;
      } else {
        // Regular paragraph — check for inline confidence badges
        let renderText = trimmed.replace(/\*\*/g, "");
        const badge = renderConfidenceBadge(doc, renderText, doc.page.width - 140, y + 1);
        if (badge) renderText = badge.cleanText;

        doc
          .font("Helvetica")
          .fontSize(10)
          .fillColor("#1a1a1a")
          .text(renderText, 60, y, { width: doc.page.width - 120, lineGap: 3 });
        y = doc.y + 8;
      }
    }
  }

  return y;
}

// ============================================================
// SOURCES SECTION
// ============================================================
function renderSources(doc, citations, y) {
  if (!citations || citations.length === 0) return;

  y = checkPageBreak(doc, y, 120);
  y += 16;

  doc
    .moveTo(60, y)
    .lineTo(doc.page.width - 60, y)
    .strokeColor("#e0e0e0")
    .lineWidth(0.5)
    .stroke();
  y += 16;

  doc
    .font("Helvetica-Bold")
    .fontSize(12)
    .fillColor(NAVY)
    .text("SOURCES", 60, y);
  y = doc.y + 10;

  // Limit citations
  const limitedCitations = citations.slice(0, MAX_CITATIONS);
  const overflow = citations.length - MAX_CITATIONS;

  for (let i = 0; i < limitedCitations.length; i++) {
    y = checkPageBreak(doc, y, 40);

    const citationText = safeText(limitedCitations[i]);
    if (!citationText) continue;

    doc
      .font("Helvetica")
      .fontSize(8)
      .fillColor("#4a90d9")
      .text(`[${i + 1}] ${citationText}`, 60, y, {
        width: doc.page.width - 120,
        link: citationText.startsWith("http") ? citationText : undefined,
      });
    y = doc.y + 3;
  }

  if (overflow > 0) {
    y += 4;
    doc
      .font("Helvetica-Oblique")
      .fontSize(8)
      .fillColor("#94a3b8")
      .text(`... and ${overflow} additional source${overflow === 1 ? "" : "s"}`, 60, y, {
        width: doc.page.width - 120,
      });
  }
}


